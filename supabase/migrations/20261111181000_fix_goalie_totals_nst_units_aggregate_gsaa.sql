-- Defects in the baseline definition (production_schema_baseline.sql:11399-11404):
--   1. NST goalie TOI (nst_*_counts_toi) is decimal MINUTES, but every NST rate multiplied by 3600 as if it were
--      seconds, so nst_all_gaa, nst_all_shots_against_per_60, nst_all_saves_per_60, nst_all_gsaa_per_60,
--      nst_all_xg_against_per_60, nst_5v5_gaa, nst_5v5_gsaa_per_60 and nst_5v5_xg_against_per_60 were 60x too large.
--      Now: x * 3600 / (sum(minutes) * 60), an explicit minutes-to-seconds conversion.
--   2. nst_all_gsaa, nst_5v5_gsaa, nst_all_hd_gsaa and nst_5v5_hd_gsaa summed NST's per-game GSAA. Decision 10:
--      GSAA = shots against x (1 - league SV%) - goals against, computed once over the aggregate. League SV% is
--      the same strength (all / 5v5; high-danger for the HD columns), the same season and the goalie's own
--      first-to-last appearance date, over league appearances whose shots and goals are present (the same
--      baseline as the goalie matrix, web/lib/rankings/goalieMatrix.ts leagueGoalsPerShotForWindow).
--   3. Rule 13: each rewritten value is NULL unless every game row in the goalie-season has its inputs (no sum over
--      one set of games divided by exposure from another). Rule 5: unknown stays NULL.
-- Unchanged: every other column, the column names, order and types (nst_*_toi stays summed NST minutes), grants,
-- and the dependent materialized view goalie_totals_unified_snapshot (it keeps its stored rows until refreshed;
-- a refresh is a separate approval). No data is written.
--
-- Readers: no application code reads goalie_totals_unified or goalie_totals_unified_snapshot (only
-- web/lib/supabase/database-generated.types.ts). Dependent: materialized view goalie_totals_unified_snapshot.
--

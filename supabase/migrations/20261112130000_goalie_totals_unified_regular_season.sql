-- Defect exposed by 135 in production: public.goalie_totals_unified aggregates every row of
-- vw_goalie_stats_unified_source, playoffs included. Playoff appearances have no NST goalie rows, so the rule-13
-- complete-support test blanked every NST value for goalies who played in the playoffs (2025-26: only 73 of 98
-- goalie-seasons carried nst_5v5_gaa and 53 nst_all_gsaa; the three busiest goalies were NULL). It also mixed
-- playoff games into GP / W / L / SV totals and stretched the GSAA league window into the playoffs.
-- Fix: game_data keeps only regular-season appearances, the rule of 125 (decision 69): the row's season has a
-- regular-season game (games.type = 2, games."seasonId" = season_id) on the row's date. Because game_data feeds
-- the totals, the NST sums, league_daily and league_window alike, every column is now regular-season only.
-- Everything else is the 135 body unchanged: column names, order and types, NST units, aggregate GSAA, rule-13
-- NULLs (a regular-season appearance without NST still blanks that goalie's NST values). The dependent
-- materialized view goalie_totals_unified_snapshot keeps its stored rows until a separately approved refresh.
-- Readers: no application code (web/, functions/); only database-generated.types.ts and the snapshot. No data is
-- written.
--
-- READBACK (after apply):

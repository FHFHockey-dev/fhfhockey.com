-- D4 future-object defaults. ISOLATED disposable canonical replay ONLY.
-- Requires pgTAP and the separately reviewed proposal; never apply it from this test.
-- Run as postgres (the creator role established in baseline source). Every probe rolls back.
BEGIN;
SET LOCAL ROLE postgres;
SET LOCAL search_path = public, extensions, pg_temp;
SELECT no_plan();

CREATE TABLE public.data_api_grants_default_probe(id bigint GENERATED BY DEFAULT AS IDENTITY, payload text);
CREATE FUNCTION public.data_api_grants_default_probe() RETURNS integer
LANGUAGE sql SECURITY INVOKER SET search_path = '' AS 'SELECT 1';

SELECT ok(NOT has_table_privilege(r.role,'public.data_api_grants_default_probe',p.op),
  format('future postgres public table: %s denied %s until explicit grant',r.role,p.op))
FROM (VALUES ('anon'),('authenticated'),('service_role')) r(role)
CROSS JOIN (VALUES ('SELECT'),('INSERT'),('UPDATE'),('DELETE'),('TRUNCATE'),('REFERENCES'),('TRIGGER')) p(op);
SELECT ok(NOT has_sequence_privilege(r.role,'public.data_api_grants_default_probe_id_seq',p.op),
  format('future postgres public sequence: %s denied %s until explicit grant',r.role,p.op))
FROM (VALUES ('anon'),('authenticated'),('service_role')) r(role)
CROSS JOIN (VALUES ('USAGE'),('SELECT'),('UPDATE')) p(op);
SELECT ok(NOT has_function_privilege(r.role,'public.data_api_grants_default_probe()','EXECUTE'),
  r.role || ' cannot execute future postgres function without explicit grant')
FROM (VALUES ('anon'),('authenticated'),('service_role')) r(role);
SELECT ok(NOT EXISTS (
  SELECT 1 FROM pg_proc p,
    LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
  WHERE p.oid='public.data_api_grants_default_probe()'::regprocedure
    AND a.grantee=0 AND a.privilege_type='EXECUTE'
), 'future function has no implicit PUBLIC EXECUTE (global default checked)');

SELECT * FROM finish();
ROLLBACK;

"""Generate the read-only hosted preflight/postcheck SQL for the D4 runbook (no database access).

The reviewed object set and expected privileges come from supabase/tests/data_api_grants.sql, which
is cross-checked here against migration 90 (same 76 tables, 46 functions and one sequence).

    python3 -I make_hosted_sql.py        writes hosted-preflight.sql and hosted-postcheck.sql here
"""
from pathlib import Path
import re

base = Path(__file__).resolve().parent
repo = base.parents[3]
matrix = (repo / 'supabase/tests/data_api_grants.sql').read_text()
m90 = (repo / 'supabase/migrations/20261020224600_data_api_reviewed_object_grants.sql').read_text()

rows = re.findall(r"\('(public\.[a-z0-9_]+)',(ARRAY\[[^]]*\]::text\[\]),(ARRAY\[[^]]*\]::text\[\]),(ARRAY\[[^]]*\]::text\[\])\)", matrix)
funcs = re.findall(r"\('(public\.[a-z0-9_]+\([^)]*\))'\)", matrix)
no_service = re.findall(r"SET service_execute=false\s+WHERE signature='([^']+)'", matrix)
sequence = 'public.roster_optimizer_team_games_id_seq'
names90 = set(re.findall(r'public\.([a-z0-9_]+)', re.sub(r'--[^\n]*', '', m90)))
assert len(rows) == 76 and len(funcs) == 46 and no_service == ['public.promote_player_forecast_model_atomic(text,uuid,uuid,text,jsonb,timestamptz)']
assert names90 == {r[0][7:] for r in rows} | {f[7:].split('(')[0] for f in funcs} | {sequence[7:]}, 'matrix and migration 90 disagree'

table_values = ',\n'.join(f"  ('{n}', {s}, {a}, {u})" for n, s, a, u in rows)
func_values = ',\n'.join(f"  ('{f}', {'false' if f in no_service else 'true'})" for f in funcs)
header = """-- Generated by make_hosted_sql.py from supabase/tests/data_api_grants.sql (cross-checked against
-- migration 20261020224600). READ-ONLY: every statement is a SELECT. Not executed on hosted by Claude.
"""

(base / 'hosted-preflight.sql').write_text(header + f"""-- D4 hosted PREFLIGHT, run before migration 89. Expected results are in REPORT.md (runbook).

-- P1. Transport identity and server version.
select current_user, session_user, current_setting('server_version') as server_version;

-- P2. Reviewed objects that migration 90 names but that do not exist. Expect 0 rows; any row means 90 would abort.
with t(name) as (values
{',\n'.join(f"  ('{n}')" for n, *_ in rows)}
), f(sig) as (values
{',\n'.join(f"  ('{x}')" for x in funcs)}
)
select 'table' as kind, name as object from t where to_regclass(name) is null
union all
select 'sequence', '{sequence}' where to_regclass('{sequence}') is null
union all
select 'function', sig from f where to_regprocedure(sig) is null
order by 1, 2;

-- P3. Every default-privilege entry (all owner roles, all schemas). Record the output.
select pg_get_userbyid(d.defaclrole) as owner_role, coalesce(n.nspname, '<all schemas>') as schema_name,
       d.defaclobjtype as object_type, coalesce(g.rolname, 'PUBLIC') as grantee,
       string_agg(a.privilege_type, ',' order by a.privilege_type) as privileges
from pg_default_acl d
left join pg_namespace n on n.oid = d.defaclnamespace
cross join lateral aclexplode(d.defaclacl) a
left join pg_roles g on g.oid = a.grantee
group by 1, 2, 3, 4
order by 1, 2, 3, 4;

-- P4. Current PUBLIC/anon/authenticated/service_role privileges on the reviewed objects (rollback reference).
select 'relation' as kind, c.oid::regclass::text as object, coalesce(g.rolname, 'PUBLIC') as grantee,
       string_agg(a.privilege_type, ',' order by a.privilege_type) as privileges
from pg_class c
cross join lateral aclexplode(coalesce(c.relacl, acldefault(case when c.relkind = 'S' then 's' else 'r' end::"char", c.relowner))) a
left join pg_roles g on g.oid = a.grantee
where c.oid = any (array[
{',\n'.join(f"  to_regclass('{n}')" for n, *_ in rows)},
  to_regclass('{sequence}')]::oid[])
  and coalesce(g.rolname, 'PUBLIC') in ('PUBLIC', 'anon', 'authenticated', 'service_role')
group by 1, 2, 3
union all
select 'function', p.oid::regprocedure::text, coalesce(g.rolname, 'PUBLIC'),
       string_agg(a.privilege_type, ',' order by a.privilege_type)
from pg_proc p
cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
left join pg_roles g on g.oid = a.grantee
where p.oid = any (array[
{',\n'.join(f"  to_regprocedure('{x}')" for x in funcs)}]::oid[])
  and coalesce(g.rolname, 'PUBLIC') in ('PUBLIC', 'anon', 'authenticated', 'service_role')
group by 1, 2, 3
order by 1, 2, 3;

-- P5. Sessions holding a transaction open for over a minute (advisory: 89/90 use lock_timeout 5s).
select pid, usename, state, now() - xact_start as xact_age, left(query, 80) as query
from pg_stat_activity
where xact_start < now() - interval '1 minute' and pid <> pg_backend_pid()
order by xact_start;
""")

(base / 'hosted-postcheck.sql').write_text(header + f"""-- D4 hosted POSTCHECK. Q1-Q2 after migration 89; Q3 after migration 90. Expected results are in REPORT.md.

-- Q1. Default ACL entries for postgres in public that still grant to a Data API role. Expect 0 rows.
select coalesce(g.rolname, 'PUBLIC') as grantee, d.defaclobjtype as object_type, a.privilege_type
from pg_default_acl d
cross join lateral aclexplode(d.defaclacl) a
left join pg_roles g on g.oid = a.grantee
where d.defaclrole = 'postgres'::regrole and d.defaclnamespace = 'public'::regnamespace
  and coalesce(g.rolname, 'PUBLIC') in ('PUBLIC', 'anon', 'authenticated', 'service_role')
order by 1, 2, 3;

-- Q2. postgres's global function default. Expect exactly 1 row with public_execute = false.
select d.defaclacl::text as acl,
       exists (select 1 from aclexplode(d.defaclacl) a where a.grantee = 0) as public_execute
from pg_default_acl d
where d.defaclrole = 'postgres'::regrole and d.defaclnamespace = 0 and d.defaclobjtype = 'f';

-- Q3. Every mismatch against the reviewed matrix (the 1,870 data_api_grants.sql expectations). Expect 0 rows.
with t(name, service_ops, anon_ops, authenticated_ops) as (values
{table_values}
), f(sig, service_execute) as (values
{func_values}
), r(role) as (values ('anon'), ('authenticated'), ('service_role')),
tops(op) as (values ('SELECT'), ('INSERT'), ('UPDATE'), ('DELETE'), ('TRUNCATE'), ('REFERENCES'), ('TRIGGER')),
sops(op) as (values ('USAGE'), ('SELECT'), ('UPDATE'))
select 'table' as kind, t.name as object, r.role, tops.op,
       op = any (case r.role when 'service_role' then t.service_ops when 'anon' then t.anon_ops else t.authenticated_ops end) as expected
from t cross join r cross join tops
where has_table_privilege(r.role, t.name, tops.op)
   <> (op = any (case r.role when 'service_role' then t.service_ops when 'anon' then t.anon_ops else t.authenticated_ops end))
union all
select 'rls', t.name, null, 'relrowsecurity', true
from t join pg_class c on c.oid = t.name::regclass where not c.relrowsecurity
union all
select 'function', f.sig, r.role, 'EXECUTE', r.role = 'service_role' and f.service_execute
from f cross join r
where has_function_privilege(r.role, f.sig, 'EXECUTE') <> (r.role = 'service_role' and f.service_execute)
union all
select 'function-public', f.sig, 'PUBLIC', 'EXECUTE', false
from f join pg_proc p on p.oid = f.sig::regprocedure
where exists (select 1 from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
              where a.grantee = 0 and a.privilege_type = 'EXECUTE')
union all
select 'sequence', '{sequence}', r.role, sops.op, r.role = 'service_role' and sops.op = 'USAGE'
from r cross join sops
where has_sequence_privilege(r.role, '{sequence}', sops.op) <> (r.role = 'service_role' and sops.op = 'USAGE')
order by 1, 2, 3, 4;
""")
print('wrote hosted-preflight.sql and hosted-postcheck.sql')

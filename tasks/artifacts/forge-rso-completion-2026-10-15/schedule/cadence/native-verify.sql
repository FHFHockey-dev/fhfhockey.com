DO $$
DECLARE today date:=(clock_timestamp() AT TIME ZONE 'America/New_York')::date;
 start_at timestamptz:=clock_timestamp()+interval '10 minutes';
 receipt jsonb; result jsonb; q public.forge_game_update_queue; n int; owner uuid:=gen_random_uuid();
 baseline_run uuid:=gen_random_uuid(); legacy_run uuid:=gen_random_uuid(); baseline_revision uuid:=gen_random_uuid(); news_key text;
BEGIN
 INSERT INTO public.games VALUES(1,start_at,1,2);
 receipt:=jsonb_build_array(jsonb_build_object('key','overnight','date',today,'status','complete',
   'revision','synthetic-r1','expectedItems',12,'completedItems',12,'completedAt',clock_timestamp()-interval '1 minute'));
 result:=public.enqueue_forge_cadence_slot(1,today,'morning',start_at,ARRAY['overnight'],jsonb_set(receipt,'{0,status}','"partial"'));
 ASSERT result->>'outcome'='held','partial upstream held';
 ASSERT (SELECT count(*) FROM public.forge_game_update_queue)=0,'held no queue writes';
 result:=public.enqueue_forge_cadence_slot(1,today,'morning',start_at,ARRAY['overnight'],receipt);
 ASSERT result->>'outcome'='enqueued','morning queued';
 result:=public.enqueue_forge_cadence_slot(1,today,'morning',start_at,ARRAY['overnight'],receipt);
 ASSERT result->>'outcome'='deduplicated','pending dedup';
 ASSERT (SELECT version FROM public.forge_game_update_queue WHERE game_id=1)=1,'dedup no new version';
 SELECT count(*) INTO n FROM public.claim_starter_board_jobs(owner,4,ARRAY[1]::bigint[]);
 ASSERT n=1,'morning claimed';
 INSERT INTO public.forge_runs VALUES(baseline_run,'succeeded',clock_timestamp(),'{}');
 INSERT INTO public.forge_game_revisions VALUES(baseline_revision,1,baseline_run,clock_timestamp(),clock_timestamp());
 PERFORM public.finish_starter_board_job(1,owner,baseline_run,NULL);
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=1;
 ASSERT q.cadence_slots->('morning:'||today::text)->>'status'='succeeded','morning success receipt';
 ASSERT (q.cadence_slots->('morning:'||today::text)->'publishedRevision'->>'revisionId')::uuid=baseline_revision,'original revision retained';
 result:=public.enqueue_forge_cadence_slot(1,today,'morning',start_at,ARRAY['overnight'],receipt);
 ASSERT result->>'outcome'='deduplicated','successful baseline not rerun';
 result:=public.enqueue_forge_cadence_slot(1,today,'news_revision',start_at,ARRAY['overnight'],receipt);
 ASSERT result->>'outcome'='enqueued','separate T-15 slot queued';
 news_key:=result->>'slotKey';
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=1;
 ASSERT (q.cadence_slots->('morning:'||today::text)->'publishedRevision'->>'revisionId')::uuid=baseline_revision,'news leaves original intact';
 ASSERT (q.cadence_slots->news_key->>'dueAt')::timestamptz=start_at-interval '15 minutes','T-15 exact';
 FOR i IN 1..3 LOOP
   UPDATE public.forge_game_update_queue SET not_before=clock_timestamp()-interval '1 minute' WHERE game_id=1;
   SELECT count(*) INTO n FROM public.claim_starter_board_jobs(owner,4,ARRAY[1]::bigint[]);
   ASSERT n=1,'failed-only bounded recovery claim';
   PERFORM public.finish_starter_board_job(1,owner,NULL,'synthetic failure');
 END LOOP;
 UPDATE public.forge_game_update_queue SET not_before=clock_timestamp()-interval '1 minute' WHERE game_id=1;
 SELECT count(*) INTO n FROM public.claim_starter_board_jobs(owner,4,ARRAY[1]::bigint[]);
 ASSERT n=0,'fourth cadence attempt blocked';
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=1;
 ASSERT q.cadence_slots->news_key->>'attempts'='3','attempts durable';
 ASSERT q.cadence_slots->news_key->>'status'='failed','exhaustion observable';
 ASSERT q.cadence_slots->('morning:'||today::text)->>'attempts'='1','success attempts untouched';
 PERFORM fhfh_internal.enqueue_starter_board_game(1,NULL,clock_timestamp(),clock_timestamp());
 UPDATE public.forge_game_update_queue SET not_before=clock_timestamp()-interval '1 minute' WHERE game_id=1;
 SELECT count(*) INTO n FROM public.claim_starter_board_jobs(owner,4,ARRAY[1]::bigint[]);
 ASSERT n=1,'new legacy news is not starved by exhausted cadence';
 INSERT INTO public.forge_runs VALUES(legacy_run,'succeeded',clock_timestamp(),'{}');
 INSERT INTO public.forge_game_revisions VALUES(gen_random_uuid(),1,legacy_run,clock_timestamp(),clock_timestamp());
 PERFORM public.finish_starter_board_job(1,owner,legacy_run,NULL);
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=1;
 ASSERT q.cadence_slots->news_key->>'status'='failed','later legacy success never certifies exhausted cadence';
 ASSERT q.cadence_slots->news_key->>'attempts'='3','later legacy transition does not spend cadence attempts';
 ASSERT NOT (q.cadence_slots->news_key ? 'publishedRevision'),'later legacy revision never credited to exhausted slot';
 INSERT INTO public.games VALUES(3,start_at,1,2);
 result:=public.enqueue_forge_cadence_slot(3,today,'morning',start_at,ARRAY['overnight'],receipt);
 UPDATE public.games SET "startTime"=start_at+interval '5 minutes' WHERE id=3;
 SELECT count(*) INTO n FROM public.claim_starter_board_jobs(owner,4,ARRAY[3]::bigint[]);
 ASSERT n=1,'reschedule claim remains fenced';
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=3;
 ASSERT q.cadence_slots->('morning:'||today::text)->>'status'='superseded','changed schedule does not certify old slot';
 INSERT INTO public.games VALUES(4,start_at,1,2);
 result:=public.enqueue_forge_cadence_slot(4,today,'morning',start_at,ARRAY['overnight'],receipt);
 PERFORM public.claim_starter_board_jobs(owner,4,ARRAY[4]::bigint[]);
 INSERT INTO public.forge_game_revisions VALUES(gen_random_uuid(),4,baseline_run,clock_timestamp(),clock_timestamp());
 UPDATE public.forge_game_update_queue SET active_run_id=baseline_run,lease_expires_at=clock_timestamp()-interval '1 second' WHERE game_id=4;
 SELECT count(*) INTO n FROM public.claim_starter_board_jobs(owner,4,ARRAY[4]::bigint[]);
 ASSERT n=0,'lost finish acknowledgement reads publication before retry';
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=4;
 ASSERT q.cadence_slots->('morning:'||today::text)->>'status'='succeeded','reconciled publication retains success';
 INSERT INTO public.games VALUES(5,start_at,1,2);
 result:=public.enqueue_forge_cadence_slot(5,today,'morning',start_at,ARRAY['overnight'],receipt);
 PERFORM fhfh_internal.enqueue_starter_board_game(5,NULL,clock_timestamp(),clock_timestamp());
 UPDATE public.forge_game_update_queue SET not_before=clock_timestamp()-interval '1 minute' WHERE game_id=5;
 PERFORM public.claim_starter_board_jobs(owner,4,ARRAY[5]::bigint[]);
 SELECT * INTO q FROM public.forge_game_update_queue WHERE game_id=5;
 ASSERT q.cadence_slots->('morning:'||today::text)->>'status'='superseded','later version supersedes uncompleted old slot';
 ASSERT q.cadence_slots->('morning:'||today::text)->>'attempts'='0','unrelated news does not spend old-slot attempts';
 RAISE NOTICE 'Native cadence assertions passed, including three bounded recovery claims';
END $$;

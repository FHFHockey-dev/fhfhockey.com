import React from "react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { act, cleanup, render, renderHook, screen } from "@testing-library/react";
const mocks=vi.hoisted(()=>({fetch:vi.fn(),pages:vi.fn()}));
vi.mock("lib/cors-fetch",()=>({default:mocks.fetch}));
vi.mock("lib/supabase",()=>({default:{from:()=>{throw new Error("Query should be intercepted by page mock");}}}));
vi.mock("lib/supabase/pagination",()=>({fetchAllSupabasePages:mocks.pages}));
vi.mock("react-chartjs-2",()=>({Doughnut:({data}:any)=><pre data-testid="chart">{JSON.stringify(data)}</pre>}));
import GoalieShareChart from "components/GoalieShareChart";
import { useShotData } from "hooks/useShotData";
afterEach(()=>{cleanup();vi.useRealTimers();vi.resetAllMocks();});
const deferred=<T,>()=>{let resolve!:(value:T)=>void;const promise=new Promise<T>(r=>{resolve=r;});return {promise,resolve};};
it("does not publish an incomplete page set as a complete season chart",async()=>{
 vi.useFakeTimers();
 const row={gameId:1,gameDate:"2026-10-01",teamAbbrev:"PHI",playerId:11,goalieFullName:"First One",gamesPlayed:1,wins:0,losses:0,otLosses:0,saves:27,shotsAgainst:30,goalsAgainst:3,timeOnIce:3600};
 mocks.fetch.mockImplementation(async(url:string)=>{const parsed=new URL(url);if(parsed.pathname.endsWith("/season"))return {ok:true,status:200,json:async()=>({data:[{id:20262027}]})};const start=Number(parsed.searchParams.get("start"));if(start===100)return {ok:false,status:429,json:async()=>({})};return {ok:true,status:200,json:async()=>({total:200,data:Array.from({length:100},(_,i)=>({...row,gameId:i+1,gameDate:new Date(Date.UTC(2025,9,1+i)).toISOString().slice(0,10)}))})};});
 render(<GoalieShareChart/>);
 await act(async()=>{await vi.advanceTimersByTimeAsync(2500);});
 const charts=screen.queryAllByTestId("chart");
 console.log("INCOMPLETE_PAGE_CHART_OBSERVED",JSON.stringify({charts:charts.map(x=>x.textContent),partialVisible:/partial|incomplete|unavailable/i.test(document.body.textContent??"")}));
 expect(charts).toHaveLength(0);
});
it("does not let an obsolete team request overwrite the cached current team's shots",async()=>{
 const pending=deferred<any[]>();
 mocks.pages.mockResolvedValueOnce([{id:1,hometeamid:1,awayteamid:99}]).mockResolvedValueOnce([{gameid:1,eventownerteamid:1,xcoord:10,ycoord:5,typedesckey:"goal"}]).mockImplementationOnce(()=>pending.promise);
 const filters={eventTypes:["goal"],gameTypes:["02"]};
 const {result,rerender}=renderHook(({team})=>useShotData(team,"20262027",filters,true),{initialProps:{team:1}});
 await act(async()=>{await Promise.resolve();await Promise.resolve();await Promise.resolve();});
 expect(result.current.shotData[0]?.eventownerteamid).toBe(1);
 rerender({team:2});
 rerender({team:1});
 mocks.pages.mockResolvedValueOnce([{gameid:2,eventownerteamid:2,xcoord:20,ycoord:5,typedesckey:"goal"}]);
 await act(async()=>{pending.resolve([{id:2,hometeamid:2,awayteamid:99}]);await Promise.resolve();await Promise.resolve();});
 console.log("SHOT_CACHE_OBSERVED",JSON.stringify({visibleTeam:1,shots:result.current.shotData,calls:mocks.pages.mock.calls.length}));
 expect(result.current.shotData[0]?.eventownerteamid).toBe(1);
});
